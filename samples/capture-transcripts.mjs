#!/usr/bin/env node
/* ============================================================================
   weeks/week05/samples/capture-transcripts.mjs — CSC 436 Week 5
   ----------------------------------------------------------------------------
   Regenerates every transcript in this folder from live servers, so nothing in
   the course materials is hand-written. Run it if you change origin.mjs or
   edge.mjs and need the printed evidence to match.

     node capture-transcripts.mjs

   It starts and stops its own origin/edge pairs on ports 8080 / 8788.
   ========================================================================== */

import { spawn } from "node:child_process";
import { appendFileSync, writeFileSync } from "node:fs";
import { setTimeout as sleep } from "node:timers/promises";
import { fileURLToPath } from "node:url";

const HERE = fileURLToPath(new URL(".", import.meta.url));
const EDGE = "http://127.0.0.1:8788";
const ORIGIN = "http://127.0.0.1:8080";
const SHOW = /^(HTTP\/|x-cache-status|x-cache-key-mode|x-served-to|age|cache-control|etag|vary|content-length)/i;

let procs = [];

function start(script, env) {
  const p = spawn(process.execPath, [script], { cwd: HERE, env: { ...process.env, ...env } });
  p.stdout.on("data", () => {});
  p.stderr.on("data", (d) => process.stderr.write(d));
  procs.push(p);
  return p;
}

function stopAll() {
  for (const p of procs) p.kill();
  procs = [];
}

async function req(url, { method = "GET", headers = {} } = {}) {
  const res = await fetch(url, { method, headers, redirect: "manual" });
  const body = await res.text();
  const lines = [`HTTP/1.1 ${res.status} ${res.statusText}`];
  for (const [k, v] of [...res.headers].sort()) if (SHOW.test(k)) lines.push(`${k}: ${v}`);
  return { lines, body, status: res.status };
}

let out = "";
const say = (s = "") => { out += s + "\n"; };

async function show(label, url, opts) {
  const { lines, body } = await req(url, opts);
  say(`$ curl -sSD - ${opts?.headers?.Cookie ? `-H 'Cookie: ${opts.headers.Cookie}' ` : ""}${url}`);
  for (const l of lines) say(l);
  const m = body.match(/Signed in as <strong>([^<]+)<\/strong> \(([^)]+)\)/);
  if (m) say(`   body: Signed in as ${m[1]} (${m[2]})`);
  say();
}

/* ------------------------------------------ transcript 1: state machine --- */

async function stateMachine() {
  out = "";
  say("CSC 436 Week 5 — shared-cache state machine, captured from edge.mjs + origin.mjs");
  say("Generated by capture-transcripts.mjs. Cache key mode: conservative.");
  say("=".repeat(78));
  say();
  say("/api/status carries: public, max-age=0, s-maxage=10.");
  say("/api/feed separately demonstrates stale extensions without s-maxage.");
  say("Its bytes only change when someone POSTs /admin/bump, so the ETag is stable");
  say("between changes -- which is what makes REVALIDATED reachable.");
  say();

  say("-".repeat(78));
  say("1. First request. Nothing stored under this key.");
  say("-".repeat(78));
  await show("miss", `${EDGE}/api/status`);

  say("-".repeat(78));
  say("2. Two seconds later. Inside s-maxage. Served from the edge store.");
  say("-".repeat(78));
  await sleep(2000);
  await show("hit", `${EDGE}/api/status`);

  say("-".repeat(78));
  say("3. Eleven seconds later. Stale. The edge sends If-None-Match; the origin");
  say("   answers 304, so the stored bytes are reused and the clock resets.");
  say("-".repeat(78));
  await sleep(11000);
  await show("revalidated", `${EDGE}/api/status`);

  say("-".repeat(78));
  say("4. The underlying data changes at the origin.");
  say("-".repeat(78));
  const bump = await fetch(`${ORIGIN}/admin/bump`, { method: "POST" });
  say(`$ curl -sS -X POST ${ORIGIN}/admin/bump`);
  say(await bump.text());

  say("-".repeat(78));
  say("5. Eleven seconds later. Stale again -- but now the ETag does NOT match,");
  say("   so the origin returns a full 200 and the edge stores the new bytes.");
  say("-".repeat(78));
  await sleep(11000);
  await show("expired", `${EDGE}/api/status`);

  say("-".repeat(78));
  say("6. /api/now emits a new timestamp on every request, so its ETag never");
  say("   repeats. A validator cannot help. It goes MISS -> EXPIRED forever,");
  say("   and every expiry costs a full payload.");
  say("-".repeat(78));
  await show("now-1", `${EDGE}/api/now`);
  await sleep(11000);
  await show("now-2", `${EDGE}/api/now`);

  say("-".repeat(78));
  say("7. The content-addressed asset. Cached for a year, and it never needs a");
  say("   purge, because changing the bytes changes the URL.");
  say("-".repeat(78));
  await show("asset-1", `${EDGE}/assets/app.c4c61eeb.js`);
  await show("asset-2", `${EDGE}/assets/app.c4c61eeb.js`);

  writeFileSync(`${HERE}cache-state-machine.txt`, out);
  console.log("wrote cache-state-machine.txt");
}

/* --------------------------------------------- transcript 2: poisoning --- */

async function poisoning() {
  out = "";
  say("CSC 436 Week 5 — the two mistakes that serve a logged-in page to a stranger");
  say("Generated by capture-transcripts.mjs.");
  say("=".repeat(78));
  say();
  say("Mistake 1 (origin):  /account is advertised `public, max-age=60` and loses");
  say("                     its `Vary: Cookie`.        -> LEAK=1");
  say("Mistake 2 (edge):    the cache key does not include the session cookie.");
  say("                     -> CACHE_KEY=vary-only or url-only");
  say();
  say("Neither mistake alone is an incident. Both together is a disclosure.");
  say();

  const scenarios = [
    ["A", "0", "vary-only", "origin correct  + standards-minimal key"],
    ["B", "1", "conservative", "origin LEAKING  + conservative key"],
    ["C", "1", "vary-only", "origin LEAKING  + standards-minimal key"],
    ["D", "1", "url-only", "origin LEAKING  + URL-only key"],
  ];

  for (const [id, leak, mode, label] of scenarios) {
    stopAll();
    await sleep(400);
    start("origin.mjs", { LEAK: leak });
    await sleep(700);
    start("edge.mjs", { CACHE_KEY: mode });
    await sleep(700);

    say("-".repeat(78));
    say(`SCENARIO ${id}: ${label}`);
    say(`         LEAK=${leak}  CACHE_KEY=${mode}`);
    say("-".repeat(78));
    await show("alice", `${EDGE}/account`, { headers: { Cookie: "sid=sid-alice" } });
    await show("bob", `${EDGE}/account`, { headers: { Cookie: "sid=sid-bob" } });
  }

  stopAll();
  say("=".repeat(78));
  say("A and B are safe. C and D hand Bob a page whose x-served-to header still");
  say("says S0198442 -- Alice's campus ID. The cache did exactly what it was told.");
  writeFileSync(`${HERE}cache-poisoning.txt`, out);
  console.log("wrote cache-poisoning.txt");
}

/* ------------------------------------------------------------------ run --- */

try {
  start("origin.mjs", { LEAK: "0" });
  await sleep(800);
  start("edge.mjs", { CACHE_KEY: "conservative" });
  await sleep(800);
  await stateMachine();
  await poisoning();
} finally {
  stopAll();
}
